// Writes the land outline used behind the map as an SVG path. Natural Earth
// 1:110m, public domain, read from the world-atlas package. Longitude and
// latitude map straight to x and y, so a drag on the map is a lat/lon box with no
// projection maths. Rounded to 0.1 degree, which is far below what 110m resolves.
//
//   node scripts/data/build-land.ts
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import type { MultiPolygon, Polygon } from "geojson";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";

const OUT = "src/lib/data/land-path.ts";
const require = createRequire(import.meta.url);
const topology = JSON.parse(
	readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"),
) as Topology<{ land: GeometryCollection }>;

const land = feature(topology, topology.objects.land);
const polygons = land.features.flatMap((item) => {
	const geometry = item.geometry as Polygon | MultiPolygon;
	return geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
});

const round = (value: number) => Number(value.toFixed(1));
const ring = (points: number[][]) =>
	`M${points.map(([lon = 0, lat = 0]) => `${round(lon + 180)} ${round(90 - lat)}`).join("L")}Z`;
const path = polygons.flatMap((rings) => rings.map(ring)).join("");

writeFileSync(
	OUT,
	`// Generated by scripts/data/build-land.ts from Natural Earth 1:110m (public domain).\n// x = longitude + 180, y = 90 - latitude.\nexport const LAND_PATH =\n\t"${path}";\n`,
);
console.log(`${OUT}: ${path.length} characters`);
